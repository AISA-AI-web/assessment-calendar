/**
 * Builds the browser preview: the real page (Index.html + Styles.html +
 * App.html) running against the real server code (apps_script/*.gs), with the
 * in-memory Sheet and the fictional school from support/ (see runtime.js).
 * No Google account, no deployment.
 *
 *   node preview/build.mjs
 *     preview/dist/index.html     a standalone page: open it, add ?as=slt etc.
 *     preview/dist/artifact.html  the same page for a hosted viewer that supplies
 *                                 its own <!doctype>/<head>/<body>; role via #slt
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');

const SERVER = ['Util', 'Config', 'Store', 'Svc', 'Days', 'Directory', 'Import', 'Rules', 'Entries', 'Mirror', 'Api'];
const SUPPORT = ['memory_backend', 'fake_services', 'fixtures'];
const TITLE = 'Assessment Calendar Preview';
const GENERATED = '<!-- GENERATED by preview/build.mjs. Do not edit; change apps_script/, support/ or preview/runtime.js. -->';

const script = (code, name) => `<script>\n/* ---- ${name} ---- */\n${code.replace(/<\/script/gi, '<\\/script')}\n</script>`;

const index = read('apps_script/Index.html');
const match = index.match(/<body>([\s\S]*)<\/body>/);
if (!match) throw new Error('Index.html has no <body>.');
let body = match[1];
const replaceOnce = (needle, value) => {
  if (!body.includes(needle)) throw new Error('Index.html is missing ' + needle);
  body = body.replace(needle, () => value);
};
replaceOnce("<?!= typeof bootstrapJson === 'undefined' ? 'null' : bootstrapJson ?>", 'null');
replaceOnce("<?!= typeof paramsJson === 'undefined' ? '{}' : paramsJson ?>", '{}');
replaceOnce("<?!= include('App') ?>", [
  ...SERVER.map((f) => script(read(`apps_script/${f}.gs`), `apps_script/${f}.gs`)),
  ...SUPPORT.map((f) => script(read(`support/${f}.js`), `support/${f}.js`)),
  script(read('preview/runtime.js'), 'preview/runtime.js'),
  read('apps_script/App.html')
].join('\n'));
if (/<\?/.test(body)) throw new Error('An Apps Script scriptlet was left in the preview.');

const fonts = [
  '<link rel="preconnect" href="https://fonts.googleapis.com">',
  '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>',
  '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=DM+Sans:wght@400;500;700&display=swap">'
].join('\n');
const styles = read('apps_script/Styles.html');

const standalone = [
  '<!DOCTYPE html>', '<html lang="en">', '<head>', GENERATED,
  '<meta charset="utf-8">', '<meta name="viewport" content="width=device-width, initial-scale=1">',
  `<title>${TITLE}</title>`, fonts, styles, '</head>', '<body>', body, '</body>', '</html>', ''
].join('\n');

// The hosted viewer cannot print, so its copy hides the Print button.
const artifact = [
  `<title>${TITLE}</title>`, GENERATED, fonts, styles,
  '<style>.btn--print { display: none !important; }</style>', body, ''
].join('\n');

mkdirSync(join(root, 'preview/dist'), { recursive: true });
writeFileSync(join(root, 'preview/dist/index.html'), standalone);
writeFileSync(join(root, 'preview/dist/artifact.html'), artifact);
console.log('Wrote preview/dist/index.html and preview/dist/artifact.html (' + Math.round(standalone.length / 1024) + ' KB)');
